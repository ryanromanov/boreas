C     COMMON BLOCKS AND BLOCK DATA: SHARED STATE UNDER DIFFERENT NAMES.
      BLOCK DATA INIT
      INTEGER SEED, COUNT
      REAL TABLE(3)
      COMMON /STATE/ SEED, COUNT, TABLE
      DATA SEED, COUNT /7, 0/
      DATA TABLE /1.5, 2.5, 3.5/
      END

      SUBROUTINE BUMP(STEP)
      INTEGER STEP, S, N
      REAL T(3)
      COMMON /STATE/ S, N, T
      S = S + STEP
      N = N + 1
      T(N) = T(N) * 2.0
      END

      INTEGER FUNCTION NEXT()
      INTEGER SEED, COUNT
      REAL TABLE(3)
      COMMON /STATE/ SEED, COUNT, TABLE
      SEED = MOD(SEED * 5, 17)
      NEXT = SEED
      END

      PROGRAM MAIN
      INTEGER SEED, COUNT, NEXT, K
      REAL TABLE(3)
      COMMON /STATE/ SEED, COUNT, TABLE
      INTEGER LOOSE
      COMMON LOOSE
      LOOSE = 3
      PRINT *, SEED, COUNT, TABLE(2)
      CALL BUMP(10)
      CALL BUMP(20)
      PRINT *, SEED, COUNT, TABLE(1), TABLE(2)
      K = NEXT() + NEXT()
      PRINT *, K, SEED, LOOSE
      END
